"""Build Comunimate/Words.lua: the ~10,000 most common English words, most common first.

    ComunimateVoice\\.venv\\Scripts\\python.exe tools\\make_words.py [--peek]

Source: the wordfreq project (https://github.com/rspeer/wordfreq). Its word
frequency data is licensed CC BY-SA 4.0, so Words.lua carries that credit
(see LICENSE). Used for word suggestions and swipe typing.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

from wordfreq import top_n_list

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "Comunimate" / "Words.lua"
COUNT = 10000

WORD = re.compile(r"^[a-z]+(?:'[a-z]+)?$")
SINGLE_OK = {"a", "i"}

# Never suggest these (slurs and the like). Ordinary swearing is left in:
# people do type it in chat.
BLOCK = {
    "nigger", "niggers", "nigga", "niggas", "fag", "fags", "faggot", "faggots", "retard", "retarded",
    "retards", "tranny", "trannies", "spic", "spics", "chink", "chinks", "kike", "kikes", "wetback",
    "gook", "gooks", "dyke", "dykes", "coon", "coons", "raghead", "towelhead", "beaner", "beaners",
}


def words() -> list[str]:
    out = []
    for w in top_n_list("en", COUNT * 2):
        if not WORD.match(w) or w in BLOCK:
            continue
        if len(w) == 1 and w not in SINGLE_OK:
            continue
        out.append(w)
        if len(out) >= COUNT:
            break
    return out


def main() -> None:
    ws = words()
    if "--peek" in sys.argv:
        print(len(ws), ws[:60])
        print([w for w in ws if "'" in w][:40])
        print(ws[-20:])
        return
    lines = []
    line = ""
    for w in ws:
        if len(line) + len(w) + 1 > 100:
            lines.append(line)
            line = ""
        line += w + " "
    lines.append(line)
    body = "\n".join(l.rstrip() for l in lines)
    OUT.write_text(
        "-- The ~10,000 most common English words, most common first (generated by\n"
        "-- tools/make_words.py, do not edit). Word frequency data from the wordfreq\n"
        "-- project (https://github.com/rspeer/wordfreq), CC BY-SA 4.0.\n\n"
        "local _, ns = ...\n"
        "ns.Dictionary = ns.Dictionary or {}\n"
        "ns.Dictionary.english = [[\n" + body + "\n]]\n",
        encoding="utf-8",
    )
    print(f"wrote {len(ws)} words to {OUT} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
